#!/usr/bin/env bash
# P2 AdGuard ECS baseline setup — supports Alibaba Cloud Linux 3 / RHEL family (dnf) and
# Ubuntu 24.04 (apt). Idempotent; safe to re-run. Run as root.
set -euo pipefail

BASE=/opt/adguard
RELEASE_USER=adguard

echo "[1/7] base packages"
if command -v apt-get >/dev/null 2>&1; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq curl tar unzip nginx git python3 ca-certificates
  apt-get install -y -qq openjdk-21-jdk-headless || apt-get install -y -qq openjdk-17-jdk-headless
else
  dnf install -y -q curl tar unzip nginx git python3 ca-certificates >/dev/null 2>&1 || true
  dnf install -y -q java-21-openjdk-headless >/dev/null 2>&1 || \
    dnf install -y -q java-latest-openjdk-headless >/dev/null
fi

echo "[2/7] directories + user"
id -u "$RELEASE_USER" >/dev/null 2>&1 || useradd --system --shell /sbin/nologin "$RELEASE_USER"
mkdir -p "$BASE"/{releases,current,canary,data,logs,config,scripts}
chown -R "$RELEASE_USER":"$RELEASE_USER" "$BASE"

echo "[3/7] docker (redis only)"
if ! command -v docker >/dev/null 2>&1; then
  if command -v apt-get >/dev/null 2>&1; then
    apt-get install -y -qq docker.io
  else
    dnf install -y -q dnf-utils
    dnf config-manager --add-repo https://mirrors.aliyun.com/docker-ce/linux/centos/docker-ce.repo >/dev/null
    dnf install -y -q docker-ce docker-ce-cli containerd.io >/dev/null
  fi
fi
systemctl enable --now docker >/dev/null 2>&1 || true

echo "[4/7] redis container (P2 private, 127.0.0.1 only)"
docker rm -f adguard-redis >/dev/null 2>&1 || true
docker run -d --name adguard-redis --restart unless-stopped \
  -p 127.0.0.1:6379:6379 \
  -v "$BASE/data/redis":/data \
  redis:7-alpine redis-server --appendonly yes --appendfsync everysec >/dev/null
echo "redis started"

echo "[5/7] nginx: public 8080 -> stable (canary 0%; switch with deploy/ecs/switch-canary.sh)"
cat > /etc/nginx/conf.d/adguard-canary.conf <<'NGINX'
# generated by deploy/ecs/switch-canary.sh; do not edit by hand
upstream adguard_stable { server 127.0.0.1:18080 max_fails=3 fail_timeout=10s; }
upstream adguard_canary { server 127.0.0.1:28080 max_fails=3 fail_timeout=10s; }

server {
    listen 8080;
    server_name _;
    client_max_body_size 128m;
    location / {
        proxy_pass http://adguard_stable;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_connect_timeout 3s;
        proxy_read_timeout 60s;
    }
    location = /healthz { proxy_pass http://adguard_stable/healthz; }
}
NGINX
nginx -t >/dev/null
systemctl enable --now nginx >/dev/null 2>&1 || true
echo "nginx configured (0% canary = all traffic to stable :18080)"

echo "[6/7] firewall (firewalld if active)"
if systemctl is-active --quiet firewalld; then
  firewall-cmd --permanent --add-port=8080/tcp >/dev/null
  firewall-cmd --permanent --add-port=22/tcp >/dev/null
  firewall-cmd --reload >/dev/null
fi

echo "[7/7] logrotate + sysctl"
cat > /etc/logrotate.d/adguard <<'ROTATE'
/opt/adguard/logs/*.log {
    daily
    rotate 14
    compress
    missingok
    notifempty
    copytruncate
}
ROTATE
cat > /etc/sysctl.d/99-adguard.conf <<'SYSCTL'
net.core.somaxconn = 4096
net.ipv4.tcp_tw_reuse = 1
vm.overcommit_memory = 1
SYSCTL
sysctl --system >/dev/null

echo "SETUP_DONE"
