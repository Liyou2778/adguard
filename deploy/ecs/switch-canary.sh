#!/usr/bin/env bash
# Switch canary traffic percentage on the ECS nginx (M6 gray release).
# Usage: bash switch-canary.sh <0|10|50|100>
#
# Note: nginx's split_clients rejects 0% / 0.0% ("invalid percent value"), so 0% is implemented
# by generating a config WITHOUT split_clients (all traffic -> stable).
set -euo pipefail
PERCENT="${1:?usage: switch-canary.sh <0|10|50|100>}"
case "$PERCENT" in
  0|10|50|100) ;;
  *) echo "unsupported percentage: $PERCENT (allowed: 0,10,50,100)"; exit 1 ;;
esac

CONF=/etc/nginx/conf.d/adguard-canary.conf
python3 - "$PERCENT" "$CONF" <<'PY'
import sys

percent, path = sys.argv[1], sys.argv[2]

upstreams = """# max_fails=0: avoid passive down-marking of a single-instance upstream after a brief restart
upstream adguard_stable { server 127.0.0.1:18080 max_fails=0; }
upstream adguard_canary { server 127.0.0.1:28080 max_fails=0; }
log_format adguard '$remote_addr $http_x_tenant_id $upstream_addr $status $request_time';
access_log /var/log/nginx/adguard-access.log adguard;"""

if percent == "0":
    split = ""
    target = "http://adguard_stable"
else:
    split = (
        'split_clients "${remote_addr}${http_x_tenant_id}" $adguard_backend {\n'
        "    %s%%     adguard_canary;\n"
        "    *        adguard_stable;\n"
        "}" % percent
    )
    target = "http://$adguard_backend"

server = """server {
    listen 8080;
    server_name _;
    client_max_body_size 128m;
    location / {
        proxy_pass %s;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_connect_timeout 3s;
        proxy_read_timeout 60s;
    }
    location = /healthz { proxy_pass %s/healthz; }
}""" % (target, target)

parts = ["# generated by deploy/ecs/switch-canary.sh; do not edit by hand", upstreams]
if split:
    parts.append(split)
parts.append(server)
open(path, "w").write("\n\n".join(parts) + "\n")
print("wrote %s (canary=%s%%)" % (path, percent))
PY

nginx -t
systemctl reload nginx
echo "canary traffic: ${PERCENT}% -> :28080, rest -> :18080"

for i in $(seq 1 10); do
  code=$(curl -s -o /dev/null -w "%{http_code}" http://127.0.0.1:8080/healthz || true)
  if [ "$code" = "200" ]; then echo "nginx healthz OK"; exit 0; fi
  sleep 1
done
echo "WARN: healthz not 200 after reload (last=$code)" >&2
exit 1
